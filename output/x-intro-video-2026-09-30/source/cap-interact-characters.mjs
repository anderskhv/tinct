const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import fs from 'fs';
const S = process.env.FILM_WORK || process.cwd();
const OUT = S + '/cap/cp-read'; fs.mkdirSync(OUT, { recursive: true });
const DT = 1000 / 24;
const browser = await chromium.launch({ args: ['--hide-scrollbars', '--mute-audio'] });
const ctx = await browser.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 2 });
await ctx.addInitScript({ path: S + '/vclock.js' });
const page = await ctx.newPage();
page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 160)); });
await page.goto('http://127.0.0.1:3001/'); await page.waitForTimeout(5000);
await page.getByRole('button', { name: 'Feature Crime and Punishment' }).click(); await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Read' }).first().click(); await page.waitForTimeout(2500);
await page.getByText('Begin reading').first().click(); await page.waitForTimeout(6000);
await page.locator("[aria-label^='Table of contents']").first().click(); await page.waitForTimeout(1500);
await page.locator("[aria-label^='Part 1, Chapter 3']").first().click(); await page.waitForTimeout(5000);
const findWord = (pref, minX = 0) => page.evaluate(([pref, minX]) => { const e = [...document.querySelectorAll('.lab-hearing-word')].find(w => w.textContent.startsWith(pref) && w.getBoundingClientRect().width > 0 && w.getBoundingClientRect().x > minX && w.getBoundingClientRect().x < 1600); if (!e) return null; const r = e.getBoundingClientRect(); return { x: r.x, y: r.y, w: r.width, h: r.height, t: e.textContent }; }, [pref, minX]);
for (let k = 0; k < 12; k++) { if (await findWord('Rodya')) break; await page.getByRole('button', { name: 'Next' }).click(); await page.waitForTimeout(1200); }
let mouse = { x: 760, y: 870 };
await page.mouse.move(mouse.x, mouse.y); await page.waitForTimeout(1500);
const rodya = await findWord('Rodya');
const dounia = await findWord('Dounia', 800);
console.log('rodya', JSON.stringify(rodya), 'dounia', JSON.stringify(dounia));
await page.evaluate(() => window.__vc.freeze());
const meta = { rodya, dounia, frames: [] };
let f = 0;
const shoot = async (label) => { await page.evaluate(ms => window.__vc.step(ms), DT); await page.evaluate(() => new Promise(r => setTimeout(r, 40))); await page.screenshot({ path: `${OUT}/i${String(f).padStart(4, '0')}.jpg`, type: 'jpeg', quality: 94 }); meta.frames.push({ f, label, mouse: { ...mouse } }); f++; };
const idle = async (n, label) => { for (let i = 0; i < n; i++) await shoot(label); };
const ease = k => k < .5 ? 4 * k * k * k : 1 - Math.pow(-2 * k + 2, 3) / 2;
const glide = async (to, n, label) => { const from = { ...mouse }; for (let i = 1; i <= n; i++) { const e = ease(i / n); mouse = { x: from.x + (to.x - from.x) * e, y: from.y + (to.y - from.y) * e }; await page.mouse.move(mouse.x, mouse.y); await shoot(label); } };
const evt = (name) => meta.frames.push({ event: name, at: f });
await idle(4, 'idle');
await glide({ x: rodya.x + 1, y: rodya.y + rodya.h / 2 }, 14, 'approachR');
await page.mouse.down(); evt('downR');
await glide({ x: rodya.x + rodya.w - 14, y: rodya.y + rodya.h / 2 }, 9, 'dragR');
await page.mouse.up(); evt('upR');
await idle(4, 'cardR');
await glide({ x: rodya.x + rodya.w + 120, y: rodya.y - 70 }, 10, 'awayR');
await idle(20, 'holdR');
// dismiss and look up Dounia
await page.mouse.click(1250, 880); evt('dismiss');
await idle(8, 'dismissed');
mouse = { x: 1250, y: 880 };
await glide({ x: dounia.x + 1, y: dounia.y + dounia.h / 2 }, 14, 'approachD');
await page.mouse.down(); evt('downD');
await glide({ x: dounia.x + dounia.w - 4, y: dounia.y + dounia.h / 2 }, 8, 'dragD');
await page.mouse.up(); evt('upD');
await idle(4, 'cardD');
await glide({ x: dounia.x + dounia.w + 140, y: dounia.y + 80 }, 10, 'awayD');
await idle(24, 'holdD');
meta.total = f;
fs.writeFileSync(OUT + '/meta.json', JSON.stringify(meta, null, 1));
console.log('frames', f);
await browser.close();
