#!/usr/bin/env node
const fs = require('fs')
const path = require('path')

const appDir = path.resolve(__dirname, '..')
const editionsDir = path.join(appDir, 'public/data/editions')
const outRoot = path.join(appDir, 'public/data/editions-chapters')
const registryPath = path.join(appDir, 'src/data/editionShardRegistry.ts')

let minKb = null
let writeRegistry = false
const targets = []
for (let i = 2; i < process.argv.length; i += 1) {
  const arg = process.argv[i]
  if (arg === '--write-registry') {
    writeRegistry = true
  } else if (arg === '--min-kb') {
    const raw = process.argv[i + 1]
    const parsed = Number(raw)
    if (!Number.isFinite(parsed) || parsed < 0) {
      throw new Error(`Invalid --min-kb value: ${raw}`)
    }
    minKb = parsed
    i += 1
  } else {
    targets.push(arg)
  }
}

if (minKb !== null) {
  for (const file of fs.readdirSync(editionsDir).sort()) {
    if (!file.endsWith('.json')) continue
    const fullPath = path.join(editionsDir, file)
    if (fs.statSync(fullPath).size >= minKb * 1024) {
      targets.push(file.replace(/\.json$/, ''))
    }
  }
}

if (targets.length === 0) {
  console.error('Usage: node scripts/split-edition-chapters.cjs [--min-kb N] [--write-registry] <bookId-editionKey> [...]')
  process.exit(1)
}

function assertSafeId(id) {
  if (!/^[a-z0-9-]+$/.test(id)) {
    throw new Error(`Unsafe edition id: ${id}`)
  }
}

const uniqueTargets = [...new Set(targets)].sort()

for (const id of uniqueTargets) {
  assertSafeId(id)
  const input = path.join(editionsDir, `${id}.json`)
  if (!fs.existsSync(input)) {
    throw new Error(`Missing edition file: ${input}`)
  }
  const data = JSON.parse(fs.readFileSync(input, 'utf8'))
  if (!data || !Array.isArray(data.chapters) || data.chapters.length === 0) {
    throw new Error(`Invalid edition file: ${input}`)
  }

  const outDir = path.join(outRoot, id)
  fs.rmSync(outDir, { recursive: true, force: true })
  fs.mkdirSync(outDir, { recursive: true })

  const lastDash = id.lastIndexOf('-')
  const secondLastDash = id.lastIndexOf('-', lastDash - 1)
  if (secondLastDash < 0) throw new Error(`Cannot infer edition key from ${id}`)
  const bookId = id.slice(0, secondLastDash)
  const editionKey = id.slice(secondLastDash + 1)

  const manifest = {
    format: 'tinct-edition-chapters-v1',
    manifestRevision: 1,
    bookId,
    editionKey,
    chapters: data.chapters.map(ch => {
      const file = `ch${String(ch.number).padStart(4, '0')}.json`
      const chapter = {
        number: ch.number,
        title: ch.title || `Chapter ${ch.number}`,
        ...(ch.section ? { section: ch.section } : {}),
        paragraphs: ch.paragraphs,
      }
      fs.writeFileSync(path.join(outDir, file), `${JSON.stringify(chapter)}\n`)
      return {
        number: ch.number,
        title: chapter.title,
        ...(ch.section ? { section: ch.section } : {}),
        path: file,
        paragraphCount: Array.isArray(ch.paragraphs) ? ch.paragraphs.length : 0,
      }
    }),
    ...(data.sections ? { sections: data.sections } : {}),
  }

  fs.writeFileSync(path.join(outDir, 'manifest.json'), `${JSON.stringify(manifest)}\n`)
  console.log(`[split-edition] ${id}: ${manifest.chapters.length} chapters`)
}

if (writeRegistry) {
  const ids = fs.readdirSync(outRoot)
    .filter(name => {
      const dir = path.join(outRoot, name)
      return fs.statSync(dir).isDirectory() && fs.existsSync(path.join(dir, 'manifest.json'))
    })
    .sort()
  const body = `// Generated by scripts/split-edition-chapters.cjs --write-registry.\n// Do not edit by hand.\nexport const CHAPTER_SHARDED_EDITION_IDS = ${JSON.stringify(ids, null, 2)} as const\n`
  fs.writeFileSync(registryPath, body)
  console.log(`[split-edition] wrote registry: ${ids.length} editions`)
}
