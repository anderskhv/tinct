#!/usr/bin/env node
// Avatars at the size they are drawn (21 Oct 2026: "profile / leaderboard images … just not good
// enough"). A painted picture (a picture set or a cover detail, src/social/profileRules.ts) is drawn
// in a round disc from the whole painting at `260% auto`: the Leaderboard and Find rows (36 CSS px)
// downloaded a 30-90 KB 480 px copy, or the 0.5-0.65 MB painting for the covers with no copy, and
// the You and profile heroes (76 CSS px) always the painting. This cuts the part each disc shows,
// once, as small square WebPs: 120 px for the rows (36 px on a 3x screen) and 240 px for the heroes
// (76 px on a 3x screen), with the content hash in the name so the Worker can let browsers keep them
// for a year (src/worker/lib/staticCache.ts). Same crop as the disc (avatarCrop in
// src/cards/avatarCache.ts, which src/social/avatarCrops.test.ts holds this script to).
//
//   node scripts/build-avatar-crops.mjs          (after adding a picture set or cover)
//
// Writes public/lab/library_2/assets/avatars/<id>-<x>-<y>-<px>-<hash>.webp and the table
// src/social/avatarCrops.generated.ts. Uses sharp, already installed with wrangler/miniflare.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const assets = resolve(here, '../public/lab/library_2/assets')
const out = join(assets, 'avatars')
const table = resolve(here, '../src/social/avatarCrops.generated.ts')
/** Drawn sizes: rows (36 CSS px) and heroes (76 CSS px), at 3x and a little over. */
export const AVATAR_CROP_SIZES = [120, 240]
export const QUALITY = 80
/** Where a cover detail sits (profileRules.pictureView 'cover'). */
const COVER_POS = '50% 38%'

/** The pictures a profile can have, from profileRules.ts itself (one source of truth). */
export function paintedPictures() {
  const source = readFileSync(resolve(here, '../src/social/profileRules.ts'), 'utf8')
  const sets = [...(source.match(/PICTURE_SETS:[^=]*=\s*\[([\s\S]*?)\n\]/)?.[1] ?? '').matchAll(/cover: `\$\{ASSETS\}\/([a-z0-9-]+)\.jpg`, pos: '([^']+)'/g)].map(m => ({ id: m[1], pos: m[2] }))
  const covers = [...(source.match(/COVER_BOOK_IDS:[^=]*=\s*\[([\s\S]*?)\]/)?.[1] ?? '').matchAll(/'([a-z0-9-]+)'/g)].map(m => ({ id: m[1], pos: COVER_POS }))
  const seen = new Set()
  return [...sets, ...covers].filter(item => { const key = `${item.id} ${item.pos}`; if (seen.has(key)) return false; seen.add(key); return true })
}

/** The key the browser looks a painted picture up by: "/lab/…/meditations.jpg 50% 34%". */
export const cropKey = (id, pos) => `/lab/library_2/assets/${id}.jpg ${pos}`

function fraction(part) {
  const value = Number.parseFloat(part ?? '50')
  return Number.isFinite(value) ? Math.min(1, Math.max(0, value / 100)) : 0.5
}

/** The disc's part of a painting drawn at `260% auto` (avatarCache.avatarCrop with cover: true). */
export function discCrop(pos, width, height) {
  const scale = 2.6 / width
  const bw = width * scale
  const bh = height * scale
  const [px, py] = pos.trim().split(/\s+/)
  const ox = (1 - bw) * fraction(px)
  const oy = (1 - bh) * fraction(py)
  const sw = Math.min(width, 1 / scale)
  const sh = Math.min(height, 1 / scale)
  const sx = Math.min(Math.max(0, -ox / scale), width - sw)
  const sy = Math.min(Math.max(0, -oy / scale), height - sh)
  return { sx, sy, sw, sh }
}

export async function buildAvatarCrops() {
  const { default: sharp } = await import('sharp')
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })
  const entries = {}
  let bytes = 0
  for (const { id, pos } of paintedPictures()) {
    const source = join(assets, `${id}.jpg`)
    const { width, height } = await sharp(source).metadata()
    const crop = discCrop(pos, width, height)
    const region = { left: Math.round(crop.sx), top: Math.round(crop.sy), width: Math.round(crop.sw), height: Math.round(crop.sh) }
    const files = {}
    for (const px of AVATAR_CROP_SIZES) {
      const data = await sharp(source).extract(region).resize(px, px, { fit: 'fill' }).webp({ quality: QUALITY }).toBuffer()
      const hash = createHash('sha256').update(data).digest('hex').slice(0, 8)
      const name = `${id}-${pos.replace(/%/g, '').replace(/\s+/g, '-')}-${px}-${hash}.webp`
      writeFileSync(join(out, name), data)
      files[px] = `/lab/library_2/assets/avatars/${name}`
      bytes += data.length
    }
    entries[cropKey(id, pos)] = files
  }
  const lines = Object.entries(entries).map(([key, files]) => `  ${JSON.stringify(key)}: { s: ${JSON.stringify(files[120])}, l: ${JSON.stringify(files[240])} },`)
  writeFileSync(table, `// Generated by scripts/build-avatar-crops.mjs; do not edit. Rerun it after adding a picture set or cover.\n/** A painted picture ("<painting> <position>") -> the disc's part as square WebPs: s 120 px (rows), l 240 px (heroes). */\nexport const AVATAR_CROPS: Readonly<Record<string, { s: string; l: string }>> = {\n${lines.join('\n')}\n}\n`)
  return { count: Object.keys(entries).length, files: readdirSync(out).length, bytes }
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const done = await buildAvatarCrops()
  console.log(`${done.count} pictures, ${done.files} files, ${Math.round(done.bytes / 1024)} KB in ${out}`)
}
