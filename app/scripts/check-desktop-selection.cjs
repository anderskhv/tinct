const { chromium, webkit } = require('playwright')
const assert = require('node:assert/strict'), fs = require('node:fs')
const origin = process.env.TEST_ORIGIN || 'http://127.0.0.1:5195'
const dir = process.env.ARTIFACT_DIR || '/tmp/tinct-desktop-selection'
fs.mkdirSync(dir, { recursive: true })
;(async () => {
  for (const [name, engine] of [['chromium', chromium], ['webkit', webkit]]) {
    const browser = await engine.launch()
    try {
      const page = await browser.newPage({ viewport: { width: 1440, height: 950 } })
      await page.route('**/api/**', route => route.fulfill({ status: 404, body: '{}' }))
      await page.addInitScript(() => sessionStorage.setItem('tinct:lab-reader-handoff', JSON.stringify({kind:'open-reader',bookId:'the-awakening',primaryEditionKey:'original-en'})))
      await page.goto(origin + '/reader')
      await page.getByTestId('lab-book-preface').getByRole('button', {name:'Begin reading',exact:true}).first().click()
      await page.waitForFunction(() => document.querySelector('.lab')?.dataset.readerReady === 'true')
      await page.evaluate(() => document.fonts.ready)
      const words = page.locator('.lab-page-wrap [data-testid="lab-word"]')
      const state = () => page.getByTestId('lab-root').evaluate(e => ({book:e.dataset.bookId,chapter:e.dataset.chapter,place:e.dataset.place}))
      const before = await state()
      await words.nth(2).click()
      await page.locator('[data-popup-mode="define"]').waitFor()
      assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('tinct-lab-highlights') || '[]').length), 0)
      await page.keyboard.press('Escape')
      const a = await words.nth(1).boundingBox(), z = await words.nth(12).boundingBox()
      await page.mouse.move(a.x+a.width/2,a.y+a.height/2)
      await page.mouse.down()
      await page.mouse.move(z.x+z.width/2,z.y+z.height/2,{steps:16})
      const selected = await page.locator('.lab-hearing-word.is-selecting').count()
      assert.ok(selected >= 12, String(selected))
      await page.mouse.up()
      await page.locator('.selection-popup').waitFor()
      const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('tinct-lab-highlights') || '[]'))
      assert.equal(saved.length,1)
      assert.equal(saved[0].color,'gold')
      await page.keyboard.press('Escape')
      assert.deepEqual(await state(),before)
      await page.screenshot({path:`${dir}/${name}-highlight.png`})
      fs.writeFileSync(`${dir}/${name}.json`,JSON.stringify({before,selected,highlight:saved[0]},null,2))
    } finally { await browser.close() }
  }
  console.log('Mouse lookup and drag-to-highlight passed in Chromium and WebKit')
})().catch(e => {console.error(e);process.exitCode=1})
