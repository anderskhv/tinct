#!/usr/bin/env node
// Chapter pages (src/seo/chapterPages.tsx): /read/{bookId}/chapter-N for every book with an unheld modern-en
// edition except the Shakespeare plays, the Modern English beside the original. Also the shelf hubs
// (/read/shelf/{shelf}) and the edition notes the book pages show. Runs in `prebuild` after build-scene-pages.mjs
// (whose page scripts the chapter pages share) and before generate-sitemap.cjs (which reads what this writes).
//
// About five thousand pages would take Cloudflare's asset count past its limit (about 18,100 files before them;
// 20,000 per deploy on the free plan), so the pages of a book are written in packs of a few hundred kilobytes, one
// file per pack, and the Worker serves one page out of its pack (src/worker/lib/chapterPages.ts).
//
// Writes (generated, not committed):
//   public/seo/chapter-packs/{bookId}/{n}.txt   chapter pages, each after <!--tinct:chapter-page N--> (N = 0: the
//                                               book page, /read/{bookId}, ahead of chapter 1); the reader's
//                                               CSS links are stamped in after vite build (stamp-scene-pages.cjs)
//   public/read/shelf/{shelf}.html              the shelf hubs
//   public/read/chapter-page.css                the chapter pages' own stylesheet
//   public/modern-english.html                  /modern-english, every book in Modern English by shelf
// and the committed manifests src/data/chapterPages.generated.json (the Worker's routes, the sitemap and the book
// pages read it) and src/data/editionNotes.generated.json (the book pages' edition notes).
// Book text is read, never written.
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const require = createRequire(import.meta.url)
const READ_DIR = join(root, 'public/read')
const PACK_DIR = join(root, 'public/seo/chapter-packs')
const HUB_DIR = join(READ_DIR, 'shelf')
const EDITIONS_DIR = join(root, 'public/data/editions')
const MANIFEST = join(root, 'src/data/chapterPages.generated.json')
const NOTES = join(root, 'src/data/editionNotes.generated.json')
/** A pack closes once it holds this many bytes (the Worker reads one pack per page view). */
export const PACK_BYTES = 400_000

const started = Date.now()
const cache = join(root, 'node_modules/.cache')
mkdirSync(cache, { recursive: true })
const rendererFile = join(cache, `chapter-pages-build-${process.pid}.mjs`)
await build({
  entryPoints: [join(root, 'src/seo/chapterPages.tsx')], bundle: true, format: 'esm', platform: 'node', target: 'node20',
  outfile: rendererFile, jsx: 'automatic', packages: 'external', loader: { '.css': 'empty' }, logLevel: 'silent',
})
const renderer = await import(pathToFileURL(rendererFile).href)
rmSync(rendererFile, { force: true })

// The scene pages' scripts (build-scene-pages.mjs wrote them), at the same versioned addresses.
const scriptUrl = {}
for (const name of ['scene-page.js', 'scene-layout.js']) {
  const file = join(READ_DIR, name)
  if (!existsSync(file)) throw new Error(`[chapter pages] ${file} is missing: run scripts/seo/build-scene-pages.mjs first`)
  scriptUrl[name] = `/read/${name}?v=${createHash('sha256').update(readFileSync(file)).digest('hex').slice(0, 10)}`
}

// The chapter pages' stylesheet, versioned by its content.
const css = renderer.chapterPageCss()
writeFileSync(join(READ_DIR, 'chapter-page.css'), css)
scriptUrl[renderer.CHAPTER_CSS_PLACEHOLDER] = `/read/chapter-page.css?v=${createHash('sha256').update(css).digest('hex').slice(0, 10)}`

const sitemap = require('../generate-sitemap.cjs')
const availability = require('../../src/data/editionAvailability.json')
const publisherPermissions = require('../../src/data/publisherPermissions.json').books
const editionFile = (bookId, key) => join(EDITIONS_DIR, `${bookId}-${key}.json`)
const available = (bookId, key) => !availability.editions[`${bookId}/${key}`] && existsSync(editionFile(bookId, key))
const readEdition = (bookId, key) => JSON.parse(readFileSync(editionFile(bookId, key), 'utf8'))

const plans = renderer.chapterPagePlans({
  available, wholeHolds: availability.wholeBooks, publisherPermissions, machineMade: sitemap.MACHINE_MADE_ORIGINALS,
})

rmSync(PACK_DIR, { recursive: true, force: true })
const manifest = { note: 'Generated by scripts/seo/build-chapter-pages.mjs. Do not hand-edit.', books: {}, hubs: {} }
let pages = 0
let indexablePages = 0
let packFiles = 0
let packBytes = 0
for (const plan of plans) {
  const modern = readEdition(plan.book.id, 'modern-en')
  const original = plan.originalKey ? readEdition(plan.book.id, plan.originalKey) : null
  const rendered = renderer.renderChapterPages({
    book: plan.book, modern, original, originalKey: plan.originalKey,
    note: plan.source ? renderer.editionNoteHtml(plan.source) : null, indexable: plan.indexable, bookPage: true,
  })
  const dir = join(PACK_DIR, plan.book.id)
  mkdirSync(dir, { recursive: true })
  const starts = []
  let pack = ''
  const flush = () => {
    if (!pack) return
    writeFileSync(join(dir, `${starts.length - 1}.txt`), pack)
    packFiles += 1
    packBytes += Buffer.byteLength(pack)
    pack = ''
  }
  for (const page of rendered) {
    let html = page.html
    for (const [name, url] of Object.entries(scriptUrl)) html = html.split(name === renderer.CHAPTER_CSS_PLACEHOLDER ? name : renderer.sceneAssetPlaceholder(name)).join(url)
    if (!pack) starts.push(page.chapterNumber)
    pack += `${renderer.chapterPageMarker(page.chapterNumber)}\n${html}`
    if (Buffer.byteLength(pack) >= PACK_BYTES) flush()
  }
  flush()
  // The book page (/read/{bookId}) is page 0 of the first pack: the first chapter under the book's header.
  const chapterCount = rendered.filter(page => page.chapterNumber > 0).length
  pages += rendered.length
  if (plan.indexable) indexablePages += rendered.length
  manifest.books[plan.book.id] = {
    chapters: chapterCount, bookPage: rendered.some(page => page.chapterNumber === 0), packs: starts, indexable: plan.indexable, original: plan.originalKey,
    labels: [renderer.editionLabelOf(plan.book, 'modern-en'), plan.originalKey ? renderer.editionLabelOf(plan.book, plan.originalKey) : null],
  }
}

// Shelf hubs: every book with a book page, its cover, and whether it has a Modern English edition.
const publicBooks = sitemap.loadPublicBooks().filter(book => sitemap.preferredEditionPath(book.id))
const indexableBooks = new Set(plans.filter(plan => plan.indexable).map(plan => plan.book.id))
const hubs = renderer.renderShelfHubs({
  books: publicBooks.map(book => ({
    id: book.id, title: book.title, modern: sitemap.hasModernEdition(book),
    cover: existsSync(join(root, 'public/covers/v2', `${book.id}.webp`)) ? `/covers/v2/${book.id}.webp` : null,
  })),
  indexableBooks,
})
rmSync(HUB_DIR, { recursive: true, force: true })
mkdirSync(HUB_DIR, { recursive: true })
for (const hub of hubs) {
  writeFileSync(join(HUB_DIR, `${hub.shelfId}.html`), hub.html)
  manifest.hubs[hub.shelfId] = hub.indexable
}

// /modern-english: every book with a Modern English edition, by shelf (docs/seo-brief-2026-11-19.md §6).
const modernBooks = publicBooks.filter(book => sitemap.hasModernEdition(book))
const modernHub = renderer.renderModernEnglishHub({
  books: modernBooks.map(book => ({
    id: book.id, title: book.title, author: book.author,
    cover: existsSync(join(root, 'public/covers/v2', `${book.id}.webp`)) ? `/covers/v2/${book.id}.webp` : null,
  })),
})
writeFileSync(join(root, 'public/modern-english.html'), modernHub.html)

// One book per line: a small file and a readable diff.
const lines = Object.entries(manifest.books).map(([bookId, entry]) => `  ${JSON.stringify(bookId)}: ${JSON.stringify(entry)}`)
writeFileSync(MANIFEST, `{\n "note": ${JSON.stringify(manifest.note)},\n "books": {\n${lines.join(',\n')}\n },\n "hubs": ${JSON.stringify(manifest.hubs)}\n}\n`)

// Edition notes for every public book with a known source (the book pages; plays included).
const notes = {}
for (const book of publicBooks) {
  const source = renderer.editionSourceFor(book.id)
  if (source && sitemap.hasModernEdition(book)) notes[book.id] = renderer.editionNoteHtml(source)
}
writeFileSync(NOTES, `{\n "note": "Generated by scripts/seo/build-chapter-pages.mjs. Do not hand-edit.",\n "books": {\n${Object.entries(notes).map(([id, note]) => `  ${JSON.stringify(id)}: ${JSON.stringify(note)}`).join(',\n')}\n }\n}\n`)

const unknown = plans.filter(plan => !plan.source).map(plan => plan.book.id)
const heldBack = plans.filter(plan => !plan.indexable && renderer.SEO_INDEX_ALLOWLIST.includes(plan.book.id)).map(plan => plan.book.id)
console.log(`[chapter pages] Wrote ${pages} chapter pages for ${plans.length} books in ${packFiles} packs (${(packBytes / 1e6).toFixed(1)} MB); ${indexablePages} indexable (${indexableBooks.size} books); ${hubs.length} shelf hubs (${hubs.filter(hub => hub.indexable).length} indexable) in ${((Date.now() - started) / 1000).toFixed(1)} s`)
if (heldBack.length) console.warn(`[chapter pages] Allowlisted but not indexable (edition source unknown in the registry): ${heldBack.join(', ')}`)
if (unknown.length) console.log(`[chapter pages] No edition note (source unknown in the registry): ${unknown.join(', ')}`)
