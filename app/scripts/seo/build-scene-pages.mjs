#!/usr/bin/env node
// Scene pages for five plays (src/seo/scenePages.tsx): one static page per scene at /read/{bookId}/{scene},
// built from the served modern-en edition byte for byte, with the scene's original-en text collapsed below.
// Runs in `prebuild`, before generate-sitemap.cjs (which lists the pages and links them from the book pages).
//
// Writes (all generated, not committed):
//   public/read/{bookId}/{scene}.html   the pages; the reader's CSS links are stamped in after vite build
//                                       (scripts/stamp-scene-pages.cjs)
//   public/read/scene-page.js           the page script (src/seo/scenePageClient.ts)
//   public/read/scene-layout.js         the first-paint layout and theme script (src/seo/sceneLayout.ts)
// and the committed manifest src/data/scenePages.generated.json (the Worker's routes and the sitemap read it).
// Only a book in the public list with an unheld modern-en edition gets pages. Book text is read, never written.
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const require = createRequire(import.meta.url)
const READ_DIR = join(root, 'public/read')
const EDITIONS_DIR = join(root, 'public/data/editions')
const MANIFEST = join(root, 'src/data/scenePages.generated.json')

const cache = join(root, 'node_modules/.cache')
mkdirSync(cache, { recursive: true })
const rendererFile = join(cache, `scene-pages-build-${process.pid}.mjs`)
await build({
  entryPoints: [join(root, 'src/seo/scenePages.tsx')], bundle: true, format: 'esm', platform: 'node', target: 'node20',
  outfile: rendererFile, jsx: 'automatic', packages: 'external', loader: { '.css': 'empty' }, logLevel: 'silent',
})
const renderer = await import(pathToFileURL(rendererFile).href)
rmSync(rendererFile, { force: true })

async function browserScript(entry, format) {
  const result = await build({
    entryPoints: [join(root, entry)], bundle: true, format, platform: 'browser', target: 'es2020',
    write: false, minify: true, legalComments: 'none', logLevel: 'silent',
  })
  return result.outputFiles[0].text
}
const scripts = {
  'scene-page.js': await browserScript('src/seo/scenePageClient.ts', 'esm'),
  'scene-layout.js': await browserScript('src/seo/sceneLayout.ts', 'iife'),
}
const scriptUrl = {}
for (const [name, text] of Object.entries(scripts)) {
  writeFileSync(join(READ_DIR, name), text)
  scriptUrl[name] = `/read/${name}?v=${createHash('sha256').update(text).digest('hex').slice(0, 10)}`
}

const { loadPublicBooks } = require('../generate-sitemap.cjs')
const holds = require('../../src/data/editionAvailability.json').editions
const publicBooks = new Map(loadPublicBooks().map(book => [book.id, book]))
const edition = (bookId, key) => {
  const file = join(EDITIONS_DIR, `${bookId}-${key}.json`)
  return !holds[`${bookId}/${key}`] && existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null
}

const manifest = { note: 'Generated by scripts/seo/build-scene-pages.mjs. Do not hand-edit.', books: {} }
let written = 0
for (const bookId of renderer.SCENE_PAGE_BOOKS) {
  const dir = join(READ_DIR, bookId)
  // Pages of an earlier build that this one does not write (a renamed scene, a held edition) must not linger.
  if (existsSync(dir)) for (const file of readdirSync(dir)) {
    if (file.endsWith('.html') && renderer.SCENE_SLUG_RE.test(file.slice(0, -5))) rmSync(join(dir, file))
  }
  const book = publicBooks.get(bookId)
  const modern = book && edition(bookId, 'modern-en')
  if (!book || !modern) { console.warn(`[scene pages] ${bookId}: not public or no unheld modern-en; no pages`); continue }
  const lines = existsSync(join(EDITIONS_DIR, `${bookId}-lines.json`)) ? JSON.parse(readFileSync(join(EDITIONS_DIR, `${bookId}-lines.json`), 'utf8')) : null
  const pages = renderer.renderScenePages({
    book: { id: book.id, title: book.title, author: book.author }, modern, original: edition(bookId, 'original-en'), originalLines: lines,
  })
  mkdirSync(dir, { recursive: true })
  for (const page of pages) {
    let html = page.html
    for (const [name, url] of Object.entries(scriptUrl)) html = html.split(renderer.sceneAssetPlaceholder(name)).join(url)
    writeFileSync(join(dir, `${page.slug}.html`), html)
    written += 1
  }
  manifest.books[bookId] = pages.map(page => ({ chapter: page.chapterNumber, slug: page.slug, title: page.title }))
}
// One scene per line: a small file and a readable diff when a scene changes.
const bookLines = Object.entries(manifest.books).map(([bookId, scenes]) => `  ${JSON.stringify(bookId)}: [\n${scenes.map(scene => `   ${JSON.stringify(scene)}`).join(',\n')}\n  ]`)
writeFileSync(MANIFEST, `{\n "note": ${JSON.stringify(manifest.note)},\n "books": {\n${bookLines.join(',\n')}\n }\n}\n`)
console.log(`[scene pages] Wrote ${written} scene pages for ${Object.keys(manifest.books).length} plays`)
