#!/usr/bin/env node
// Bundles the approved lifecycle email templates (docs/lifecycle-emails/
// templates/*.html and *.txt) into the Worker as string constants, so the
// approved files stay the single source and the Worker needs no file reads.
// src/worker/lifecycle/templates.test.ts fails if the bundle drifts from the
// docs. Re-run after editing a template:
//
//   node scripts/generate-email-templates.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.resolve(root, '../docs/lifecycle-emails/templates')
const names = [...new Set(fs.readdirSync(dir).filter(f => /\.(html|txt)$/.test(f)).map(f => f.replace(/\.(html|txt)$/, '')))].sort()

let out = '// Generated by scripts/generate-email-templates.mjs from docs/lifecycle-emails/templates.\n'
out += '// Do not edit by hand: edit the template and re-run the script.\n'
out += 'export const EMAIL_TEMPLATES = {\n'
for (const name of names) {
  const html = fs.readFileSync(path.join(dir, `${name}.html`), 'utf8')
  const text = fs.readFileSync(path.join(dir, `${name}.txt`), 'utf8')
  out += `  ${JSON.stringify(name)}: {\n    html: ${JSON.stringify(html)},\n    text: ${JSON.stringify(text)},\n  },\n`
}
out += '} as const\n\nexport type EmailTemplateName = keyof typeof EMAIL_TEMPLATES\n'
fs.writeFileSync(path.join(root, 'src/worker/lifecycle/templates.generated.ts'), out)
console.log(`email templates: ${names.join(', ')}`)
