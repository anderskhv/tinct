#!/usr/bin/env node
// Email art for the lifecycle emails (docs/lifecycle-emails/README.md):
// each book's library painting cropped landscape to 1200 × 600 from the top
// of the painting, as JPEG (email clients do not reliably render WebP),
// at most 150 KB. The welcome email without a book uses the library hero.
//
// Output is committed under public/email-art/ and listed in
// src/worker/lifecycle/emailArt.generated.ts, so neither the build nor the
// Worker does any image work. Re-run after adding a book or a painting:
//
//   node scripts/generate-email-art.mjs
//
// Uses sharp (already installed with wrangler/miniflare). No network.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pub = path.join(root, 'public')
const outDir = path.join(pub, 'email-art')
const MAX_BYTES = 150 * 1024
const WIDTH = 1200
const HEIGHT = 600

// The painted library set first (lab/library_2/cover-assets.js), then the
// published cover collection (public/covers/v2), preferring its 2x file.
const paintedDir = path.join(pub, 'lab/library_2/assets')
const coversDir = path.join(pub, 'covers/v2')
const painted = fs.readFileSync(path.join(pub, 'lab/library_2/cover-assets.js'), 'utf8')
  .match(/new Set\(\[([^\]]*)\]\)/)[1].match(/'([^']+)'/g).map(s => s.slice(1, -1))

const sources = new Map()
for (const file of fs.readdirSync(coversDir).sort()) {
  const match = file.match(/^([a-z0-9-]+)\.webp$/)
  if (!match) continue
  const twoX = path.join(coversDir, `${match[1]}@2x.webp`)
  sources.set(match[1], fs.existsSync(twoX) ? twoX : path.join(coversDir, file))
}
for (const id of painted) {
  const file = path.join(paintedDir, `${id}.jpg`)
  if (fs.existsSync(file)) sources.set(id, file)
}

async function topCrop(input) {
  const image = sharp(input)
  const { width, height } = await image.metadata()
  const cropHeight = Math.min(height, Math.round(width * HEIGHT / WIDTH))
  const base = sharp(input).extract({ left: 0, top: 0, width, height: cropHeight }).resize(WIDTH, HEIGHT, { fit: 'cover', position: 'top' })
  for (let quality = 84; quality >= 40; quality -= 4) {
    const buffer = await base.clone().jpeg({ quality, mozjpeg: true, progressive: true, chromaSubsampling: '4:2:0' }).toBuffer()
    if (buffer.length <= MAX_BYTES) return buffer
  }
  throw new Error(`${input}: cannot reach ${MAX_BYTES} bytes`)
}

fs.mkdirSync(outDir, { recursive: true })
const ids = [...sources.keys()].sort()
for (const id of ids) fs.writeFileSync(path.join(outDir, `${id}.jpg`), await topCrop(sources.get(id)))
fs.writeFileSync(path.join(outDir, 'library.jpg'), await topCrop(path.join(paintedDir, 'room-wide-v2.jpg')))

const list = ids.map(id => `  '${id}',`).join('\n')
fs.writeFileSync(path.join(root, 'src/worker/lifecycle/emailArt.generated.ts'),
  `// Generated by scripts/generate-email-art.mjs. Do not edit by hand.\n` +
  `/** Books with a hosted 1200 × 600 JPEG at /email-art/{id}.jpg. */\n` +
  `export const EMAIL_ART_BOOK_IDS: ReadonlySet<string> = new Set([\n${list}\n])\n`)
console.log(`email art: ${ids.length} books + library.jpg`)
