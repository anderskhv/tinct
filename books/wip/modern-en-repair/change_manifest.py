#!/usr/bin/env python3
"""Record exactly what a repaired chapter changes, for audio regeneration.

Run BEFORE writing a candidate into the live edition, while the live file
still holds the old text:

    python3 books/wip/modern-en-repair/change_manifest.py <book> <chapter> <candidate.json>

Appends one row per changed paragraph to
books/wip/modern-en-repair/manifests/<book>-changes.json and refreshes
<book>-changes.md.

Why per paragraph: Tinct audio is generated and timed per paragraph, so only
paragraphs whose text actually changed need re-recording and re-timing. A
paragraph left byte-identical keeps its existing recording and its existing
word-timing sidecar entry.
"""
import json, re, sys, difflib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ED = ROOT / "app/public/data/editions"
OUT = Path(__file__).resolve().parent / "manifests"


def norm(s):
    return re.sub(r"\s+", " ", s.replace("’", "'").replace("“", '"').replace("”", '"').replace("‘", "'")).strip()


def main():
    book, ch, cand_path = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    live = json.load(open(ED / f"{book}-modern-en.json"))["chapters"][ch - 1]["paragraphs"]
    cand = json.load(open(cand_path))
    if len(cand) != len(live):
        sys.exit(f"ABORT: candidate has {len(cand)} paragraphs, live modern-en chapter has {len(live)}")

    changed, unchanged = [], 0
    for i, (old, new) in enumerate(zip(live, cand)):
        if norm(old) == norm(new):
            unchanged += 1
            continue
        changed.append({
            "paragraph": i,
            "oldWords": len(old.split()),
            "newWords": len(new.split()),
            "similarity": round(difflib.SequenceMatcher(None, norm(old), norm(new)).ratio(), 3),
        })

    OUT.mkdir(exist_ok=True)
    jpath = OUT / f"{book}-changes.json"
    data = json.loads(jpath.read_text()) if jpath.exists() else {"bookId": book, "edition": "modern-en", "chapters": {}}
    data["chapters"][str(ch)] = {
        "paragraphs": len(live),
        "changed": len(changed),
        "unchanged": unchanged,
        "audioRegenRequired": len(changed) > 0,
        "changedParagraphs": changed,
    }
    jpath.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")

    lines = [
        f"# {book} — modern-en repair: change manifest",
        "",
        "Generated by `change_manifest.py` at repair time, comparing the new",
        "rendering against the modern-en text that was live when the chapter was",
        "repaired. Drives audio regeneration: a changed paragraph needs a new",
        "Kokoro recording and a new word-timing sidecar entry; an unchanged one",
        "keeps both.",
        "",
        "| Chapter | Paragraphs | Changed | Unchanged | Audio regen |",
        "|---|---|---|---|---|",
    ]
    tot_c = tot_p = 0
    for c in sorted(data["chapters"], key=int):
        e = data["chapters"][c]
        tot_c += e["changed"]; tot_p += e["paragraphs"]
        lines.append(f"| {c} | {e['paragraphs']} | {e['changed']} | {e['unchanged']} | {'yes' if e['audioRegenRequired'] else 'no'} |")
    lines += ["", f"**Total: {tot_c} of {tot_p} paragraphs changed across {len(data['chapters'])} repaired chapter(s).**", ""]
    (OUT / f"{book}-changes.md").write_text("\n".join(lines))

    print(f"{book} ch{ch}: {len(changed)} changed, {unchanged} unchanged of {len(live)} paragraphs -> {jpath.name}")


if __name__ == "__main__":
    main()
